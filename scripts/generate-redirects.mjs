/**
 * Generate Cloudflare Pages `_redirects` from blog frontmatter + WP hub map.
 * Run: node scripts/generate-redirects.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const blogDir = path.join(root, 'src/content/blog');
const mapPath = path.join(__dirname, 'wp-category-map.json');
const outPath = path.join(root, 'public/_redirects');

function pad2(n) {
  return String(n).padStart(2, '0');
}

function parseFrontmatter(raw) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!match) return {};
  const data = {};
  for (const line of match[1].split(/\r?\n/)) {
    const m = line.match(/^(\w+):\s*(.+)$/);
    if (!m) continue;
    data[m[1]] = m[2].replace(/^['"]|['"]$/g, '');
  }
  return data;
}

function datePartsFromYaml(pubDate) {
  // Expect YYYY-MM-DD or ISO
  const m = String(pubDate).match(/^(\d{4})-(\d{2})-(\d{2})/);
  if (m) return { year: m[1], month: m[2], day: m[3] };
  const d = new Date(pubDate);
  return {
    year: String(d.getUTCFullYear()),
    month: pad2(d.getUTCMonth() + 1),
    day: pad2(d.getUTCDate()),
  };
}

const map = JSON.parse(fs.readFileSync(mapPath, 'utf8'));
const lines = [
  '# Generated by scripts/generate-redirects.mjs — do not edit by hand',
  '# Legacy /blog/:slug → date permalink',
];

for (const file of fs.readdirSync(blogDir)) {
  if (!/\.(md|mdx)$/.test(file)) continue;
  const id = file.replace(/\.(md|mdx)$/, '');
  const raw = fs.readFileSync(path.join(blogDir, file), 'utf8');
  const fm = parseFrontmatter(raw);
  if (fm.draft === 'true') continue;
  if (!fm.pubDate) continue;
  const { year, month, day } = datePartsFromYaml(fm.pubDate);
  const to = `/${year}/${month}/${day}/${id}`;
  lines.push(`/blog/${id} ${to} 301`);
}

lines.push('', '# WordPress hub / category → Astro topics & series');
for (const { from, to } of map.hubRedirects) {
  const fromPath = from.endsWith('/') ? from.slice(0, -1) : from;
  lines.push(`${fromPath} ${to} 301`);
  lines.push(`${fromPath}/ ${to} 301`);
}

lines.push('', '# Catch-all leftover WP demo pages → home');
for (const p of [
  '/shop-online',
  '/cart',
  '/checkout',
  '/my-account',
  '/investors',
  '/stock-performance',
  '/shareholder-faq',
  '/corporate-governance',
  '/corporate-faq',
  '/contact',
  '/contact-us-2',
  '/home',
  '/home-2',
  '/home-4',
  '/my-front-page',
  '/blog-2',
  '/work',
  '/sample-page-2',
]) {
  lines.push(`${p} / 301`);
  lines.push(`${p}/ / 301`);
}

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, lines.join('\n') + '\n', 'utf8');
console.log(`Wrote ${lines.length} lines to public/_redirects`);
