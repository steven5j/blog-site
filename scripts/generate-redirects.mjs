/**
 * Generate Cloudflare Pages `_redirects` from blog frontmatter + WP hub map.
 * Run: node scripts/generate-redirects.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  datePartsFromPubDate,
  parseFrontmatter,
  postHrefFromParts,
  urlSlugFromEntry,
} from './blog-slug.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const blogDir = path.join(root, 'src/content/blog');
const mapPath = path.join(__dirname, 'wp-category-map.json');
const outPath = path.join(root, 'public/_redirects');

const map = JSON.parse(fs.readFileSync(mapPath, 'utf8'));
const lines = [
  '# Generated by scripts/generate-redirects.mjs — do not edit by hand',
  '# Legacy /blog/:id and /YYYY/MM/DD/:id → ASCII date permalink',
];

/** @param {string} from @param {string} to */
function addRedirect(from, to) {
  lines.push(`${from} ${to} 301`);
  if (!from.endsWith('/')) {
    lines.push(`${from}/ ${to.endsWith('/') ? to : `${to}/`} 301`);
  }
}

for (const file of fs.readdirSync(blogDir)) {
  if (!/\.(md|mdx)$/.test(file)) continue;
  const id = file.replace(/\.(md|mdx)$/, '');
  const raw = fs.readFileSync(path.join(blogDir, file), 'utf8');
  const { meta } = parseFrontmatter(raw);
  if (meta.draft === 'true') continue;
  if (!meta.pubDate) continue;

  const urlSlug = urlSlugFromEntry(id, meta);
  const to = postHrefFromParts(meta.pubDate, urlSlug);

  addRedirect(`/blog/${id}`, to);

  if (id !== urlSlug) {
    const { year, month, day } = datePartsFromPubDate(meta.pubDate);
    addRedirect(`/${year}/${month}/${day}/${id}`, to);
  }
}

lines.push('', '# WordPress hub / category → Astro topics & series');
for (const { from, to } of map.hubRedirects) {
  const fromPath = from.endsWith('/') ? from.slice(0, -1) : from;
  addRedirect(fromPath, to);
}

lines.push('', '# Catch-all leftover WP demo pages → home');
for (const p of [
  '/shop-online',
  '/cart',
  '/checkout',
  '/my-account',
  '/investors',
  '/stock-performance',
  '/shareholder-faq',
  '/corporate-governance',
  '/corporate-faq',
  '/contact',
  '/contact-us-2',
  '/home',
  '/home-2',
  '/home-4',
  '/my-front-page',
  '/blog-2',
  '/work',
  '/sample-page-2',
]) {
  addRedirect(p, '/');
}

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, lines.join('\n') + '\n', 'utf8');
console.log(`Wrote ${lines.length} lines to public/_redirects`);
